# 自訂題目：以三種迭代格式求解黃金比例 (方程式 x^2 - x - 1 = 0)
# 理論真值 phi = (1 + 5**0.5) / 2 ≈ 1.618033988749895

f1 = lambda x: (x + 1) ** 0.5          # 根號不動點轉換 (單調線性收斂)
f2 = lambda x: 1 + 1 / x               # 倒數不動點轉換 (震盪線性收斂)
f3 = lambda x: (x * x + 1) / (2 * x - 1) # 牛頓法切線轉換 (二次極速收斂)

x1 = x2 = x3 = 1.0

print(f"{'Iter':<4} | {'x1 (根號法)':<18} | {'x2 (倒數法)':<18} | {'x3 (牛頓法)':<18}")
print("-" * 66)

for i in range(1, 21):
    x1, x2, x3 = f1(x1), f2(x2), f3(x3)
    print(f"{i:<4} | {x1:<18.15f} | {x2:<18.15f} | {x3:<18.15f}")
